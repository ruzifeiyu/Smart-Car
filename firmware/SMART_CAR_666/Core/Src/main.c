/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_TIM8_Init();
  MX_USART3_UART_Init();
  MX_TIM3_Init();
  MX_TIM1_Init();
  MX_TIM14_Init();
  /* USER CODE BEGIN 2 */
  /* CubeMX完成配置，这里只启动PWM、编码器和串口接收。 */
  if (Motor_Init() != HAL_OK)
  {
    g_app_fault = APP_FAULT_PWM;
    Error_Handler();
  }
  motor_initialized = 1U;

  if (Encoder_Init(APP_ENCODER_COUNTS_PER_REV) != HAL_OK)
  {
    g_app_fault = APP_FAULT_ENCODER;
    Error_Handler();
  }
  if (Serial_Init() != HAL_OK)
  {
    Error_Handler();
  }

  app_start_tick = HAL_GetTick();
  last_control_tick = app_start_tick;
  last_telemetry_tick = app_start_tick;
  /* 串口发送失败只记录状态，不阻止电机运行。 */
  g_serial_last_status =
      Serial_SendString("cmd1_pct,duty1_pct,cmd2_pct,duty2_pct,cmd3_pct,duty3_pct,cmd4_pct,duty4_pct,cps,delta,fault\r\n") != 0U
      ? HAL_OK : Serial_GetLastStatus();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    uint32_t now_tick;
    HAL_StatusTypeDef encoder_status;

    Serial_Proc();
    g_serial_last_status = Serial_GetLastStatus();
    now_tick = HAL_GetTick();

    if ((uint32_t)(now_tick - last_control_tick) >= APP_CONTROL_PERIOD_MS)
    {
      last_control_tick = now_tick;
      /* 20ms只用于调度，不再因单次间隔超过100ms锁定停机。 */
      encoder_status = Encoder_Update();
      if ((encoder_status != HAL_OK) && (encoder_status != HAL_BUSY))
      {
        g_app_fault = APP_FAULT_ENCODER;
        Error_Handler();
      }
      g_encoder_counts_per_second = Encoder_GetCountsPerSecond_L();
      g_encoder_delta_counts = Encoder_GetDelta_L();

      if ((uint32_t)(now_tick - app_start_tick) >= APP_START_DELAY_MS)
      {
        if (Load(g_motor1_command_percent, g_motor2_command_percent,
                 g_motor3_command_percent, g_motor4_command_percent) != HAL_OK)
        {
          g_app_fault = APP_FAULT_PWM;
          Error_Handler();
        }
      }
      g_motor1_applied_percent = Motor_GetDuty1Percent();
      g_motor2_applied_percent = Motor_GetDuty2Percent();
      g_motor3_applied_percent = Motor_GetDuty3Percent();
      g_motor4_applied_percent = Motor_GetDuty4Percent();
    }

    if ((uint32_t)(now_tick - last_telemetry_tick) >= APP_TELEMETRY_PERIOD_MS)
    {
      last_telemetry_tick = now_tick;
      g_serial_last_status =
          Serial_Printf("%ld,%lu,%ld,%lu,%ld,%lu,%ld,%lu,%ld,%ld,%lu\r\n",
                        (long)g_motor1_command_percent,
                        (unsigned long)g_motor1_applied_percent,
                        (long)g_motor2_command_percent,
                        (unsigned long)g_motor2_applied_percent,
                        (long)g_motor3_command_percent,
                        (unsigned long)g_motor3_applied_percent,
                        (long)g_motor4_command_percent,
                        (unsigned long)g_motor4_applied_percent,
                        (long)g_encoder_counts_per_second,
                        (long)g_encoder_delta_counts,
                        (unsigned long)g_app_fault) != 0U
          ? HAL_OK : Serial_GetLastStatus();
    }
  }
  /* USER CODE END 3 */
}

